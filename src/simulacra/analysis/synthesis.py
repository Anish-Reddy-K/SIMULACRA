"""Evidence-backed synthesis: findings as claims, each with its numbers and source trials.

Claims are generated by templates from computed data (no model writes a number), and
`verify` recomputes every claim's numbers independently from the stored trials.
"""

from typing import Any

from sqlalchemy.orm import Session

from simulacra.analysis import concept, themes
from simulacra.experiments.schemas import TOP_BOX
from simulacra.persistence.models import Trial

MAX_EVIDENCE = 3


def _ids(trials: list[Trial]) -> list[int]:
    return [t.id for t in trials[:MAX_EVIDENCE]]


def build(session: Session, run_id: int) -> list[dict[str, Any]]:
    _run, trials, personas, _labels = concept.load(session, run_id)
    valid = [t for t in trials if t.status == "valid" and t.parsed_json]
    claims: list[dict[str, Any]] = []
    if not valid:
        return claims
    n = len(valid)

    top = [t for t in valid if concept.parsed(t)["purchase_intent"] in TOP_BOX]
    claims.append(
        {
            "id": "overall_top2",
            "kind": "overall",
            "text": f"{len(top)} of {n} valid responses ({len(top) / n:.0%}) said probably or definitely.",
            "numbers": {"k": len(top), "n": n},
            "evidence_trial_ids": _ids(top),
            "evidence_note": "Examples of responses counted in the numerator.",
        }
    )

    ranked = concept._ranked(valid, "top_objection", exclude=("none",))
    if ranked:
        code = ranked[0]["code"]
        rows = [t for t in valid if concept.parsed(t)["top_objection"] == code]
        claims.append(
            {
                "id": "top_objection",
                "kind": "objection",
                "text": f"'{code.replace('_', ' ')}' was the most common objection: {len(rows)} of {n} responses ({len(rows) / n:.0%}).",
                "numbers": {"k": len(rows), "n": n, "code": code},
                "evidence_trial_ids": _ids(rows),
            }
        )

    overall = len(top) / n
    best: tuple[float, str, str, list[Trial]] | None = None
    groups: dict[tuple[str, str], list[Trial]] = {}
    for t in valid:
        attrs = personas.get(t.persona_id, {})
        for attribute in concept.SEGMENT_ATTRIBUTES:
            value = concept.segment_value(attrs, attribute)
            if value is not None:
                groups.setdefault((attribute, value), []).append(t)
    for (attribute, value), rows in sorted(groups.items()):
        if len(rows) < concept.MIN_SEGMENT_N:
            continue
        share = sum(concept.parsed(t)["purchase_intent"] in TOP_BOX for t in rows) / len(rows)
        gap = share - overall
        if best is None or abs(gap) > abs(best[0]):
            best = (gap, attribute, value, rows)
    if best is not None and abs(best[0]) >= 0.05:
        gap, attribute, value, rows = best
        k = sum(concept.parsed(t)["purchase_intent"] in TOP_BOX for t in rows)
        claims.append(
            {
                "id": "largest_segment_gap",
                "kind": "segment",
                "text": f"The largest segment difference was {attribute.replace('_', ' ')} = {value.replace('_', ' ')}: {k} of {len(rows)} ({k / len(rows):.0%}) versus {overall:.0%} overall. Exploratory, not adjusted for multiple comparisons.",
                "numbers": {
                    "attribute": attribute,
                    "value": value,
                    "k": k,
                    "n": len(rows),
                    "overall_k": len(top),
                    "overall_n": n,
                },
                "evidence_trial_ids": _ids(rows),
            }
        )

    clusters = themes.cluster_reasons([(t.id, concept.parsed(t)["reason"]) for t in valid])
    for i, c in enumerate(clusters[:3]):
        claims.append(
            {
                "id": f"theme_{i + 1}",
                "kind": "theme",
                "text": f'A recurring theme appears in {c.size} of {n} responses ({c.size / n:.0%}), for example: "{c.exemplar_text}"',
                "numbers": {
                    "cluster_size": c.size,
                    "n": n,
                    "exemplar_trial_id": c.exemplar_trial_id,
                },
                "evidence_trial_ids": c.trial_ids[:MAX_EVIDENCE],
            }
        )
    return claims


def verify(session: Session, run_id: int, claims: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Independently recompute each claim's numbers; returns one result per claim."""
    _run, trials, personas, _ = concept.load(session, run_id)
    valid = [t for t in trials if t.status == "valid" and t.parsed_json]
    by_id = {t.id: t for t in trials}
    out = []
    for c in claims:
        num, problems = c["numbers"], []
        if c["kind"] == "overall":
            k = sum(1 for t in valid if concept.parsed(t)["purchase_intent"] in TOP_BOX)
            if (k, len(valid)) != (num["k"], num["n"]):
                problems.append(f"expected {k}/{len(valid)}")
        elif c["kind"] == "objection":
            k = sum(1 for t in valid if concept.parsed(t)["top_objection"] == num["code"])
            if (k, len(valid)) != (num["k"], num["n"]):
                problems.append(f"expected {k}/{len(valid)}")
        elif c["kind"] == "segment":
            rows = [
                t
                for t in valid
                if concept.segment_value(personas.get(t.persona_id, {}), num["attribute"])
                == num["value"]
            ]
            k = sum(1 for t in rows if concept.parsed(t)["purchase_intent"] in TOP_BOX)
            if (k, len(rows)) != (num["k"], num["n"]):
                problems.append(f"expected {k}/{len(rows)}")
        for tid in c["evidence_trial_ids"]:
            t = by_id.get(tid)
            if t is None or t.run_id != run_id:
                problems.append(f"evidence trial {tid} not in this run")
        out.append({"id": c["id"], "verified": not problems, "problems": problems})
    return out
